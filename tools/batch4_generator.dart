      final rawAnswer = match.group(1)!.trim();
      final isMultiple = rawAnswer.contains(',');
      final answerList = isMultiple 
          ? rawAnswer.split(',').map((e) => int.parse(e.trim())).toList()
          : [int.parse(rawAnswer)];

      // 1~32 題配電盤，33~65 題照明，66~179 題電動機
      String workItem = count < 32 
          ? "工作項目09：配電盤、儀表工程裝修" 
          : (count < 65 ? "工作項目10：照明工程裝修" : "工作項目11：電動機工程裝修");

      outputList.add({
        "id": "Q-00700-B4-${(count + 1).toString().padLeft(4, '0')}",
        "category": "00700_B",
        "categoryLabel": "乙級室內配線",
        "workItem": workItem,
        "type": isMultiple ? "multiple" : "single",
        "difficulty": count >= 65 ? 3 : 2,
        "isFree": false,
        "question": match.group(2)!.trim(),
        "options": [
          match.group(3)!.trim().replaceAll('。', ''),
          match.group(4)!.trim().replaceAll('。', ''),
          match.group(5)!.trim().replaceAll('。', ''),
          match.group(6)!.trim().replaceAll('。', '')
        ],
        "answer": answerList,
        "explanation": {
          "quickHack": isMultiple ? "⚠️ 必考複選題：記熟配電與馬達運轉條件" : "⚡ 官方標準答案代號：$rawAnswer",
          "formula": "勞動部 007002A15 官方檢定標準規範",
          "stepByStep": "依據技能檢定中心官方公布標準答案為選項 $rawAnswer。",
          "fieldNote": "配電盤連動保護與三相電動機控制為術科配線之根基，務必融會貫通。"
        }
      });
      count++;
    }
  }

  final outputFile = File('batch4_questions.json');
  outputFile.writeAsStringSync(jsonEncode(outputList));
  print('✅ [Batch 4/5] 壓製完成！成功生成 $count 道真實試題。');
  print('📁 匯出檔案：${outputFile.absolute.path}');
}
